// Pre-compute pixel lists + trimmed width for each glyph.
const GLYPHS = {};
for (const [ch, rows] of Object.entries(RAW)) {
  const grid = rows.split(' ');
  const pixels = [];
  let maxX = 0;
  grid.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === '#') { pixels.push([x, y]); maxX = Math.max(maxX, x); }
  }));
  GLYPHS[ch] = { pixels, width: maxX + 1 };
}
const SPACE = 3;
const HEIGHT = 7;

const glyphFor = (ch) => GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];

/** Width in px of text at a given scale. */
function measureText(text, scale) {
  let w = 0;
  for (const ch of String(text)) w += (ch === ' ' ? SPACE : glyphFor(ch).width) * scale + scale;
  return Math.max(0, w - scale);
}

/**
 * Draw pixel text. y is the TOP of the text.
 * opts: align ('left'|'center'|'right'), shadow (bool | colour)
 */
function drawText(ctx, text, x, y, scale, color, { align = 'left', shadow = true } = {}) {
  const str = String(text);
  const w = measureText(str, scale);
  if (align === 'center') x -= w / 2;
  if (align === 'right') x -= w;
  x = Math.round(x);
  y = Math.round(y);

  const pass = (ox, oy, fill) => {
    ctx.fillStyle = fill;
    let cx = x + ox;
    for (const ch of str) {
      if (ch === ' ') { cx += (SPACE + 1) * scale; continue; }
      const g = glyphFor(ch);
      for (const [px, py] of g.pixels) ctx.fillRect(cx + px * scale, y + oy + py * scale, scale, scale);
      cx += (g.width + 1) * scale;
    }
  };
  if (shadow) pass(scale, scale, typeof shadow === 'string' ? shadow : 'rgba(0,0,0,0.45)');
  pass(0, 0, color);
  return w;
}

module.exports = { drawText, measureText, HEIGHT };
